"""A shared company entry link and class code, scoped to listed trainees."""
import hashlib
import secrets

import psycopg2.extras

from .core import get_db


def _digest(value):
    return hashlib.sha256(value.encode()).hexdigest()


def issue_registration_token(intake_id, created_by=None, with_class=False):
    """Issue a link and ensure its class/code exist in the SAME transaction.

    Replacing a link reuses the open class and its code. The optional response
    includes the code so staff can share both immediately, without another action.
    """
    from .classes import _new_code
    from .lms import normalize_training_type
    token = secrets.token_urlsafe(32)
    conn = get_db(); cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
    try:
        cur.execute("SELECT * FROM corporate_intakes WHERE id=%s "
                    "AND status IN ('open','ready') FOR UPDATE", (intake_id,))
        intake = cur.fetchone()
        if not intake:
            conn.rollback()
            return None
        program = normalize_training_type(intake['form_type'], intake['training_type'])
        cur.execute("""SELECT * FROM training_classes
                         WHERE intake_id=%s AND program_code=%s AND join_open=TRUE
                         ORDER BY (corporate_payment_id IS NOT NULL) DESC, id
                         LIMIT 1 FOR SHARE""", (intake_id, program))
        cls = cur.fetchone()
        if not cls:
            cur.execute("""SELECT id FROM corporate_payments WHERE intake_id=%s
                             ORDER BY (status='paid') DESC, created_at DESC, id DESC LIMIT 1""",
                        (intake_id,))
            invoice = cur.fetchone()
            from pricing import program_label
            for _ in range(8):
                cur.execute("""INSERT INTO training_classes
                       (name, training_type, program_code, intake_id,
                        corporate_payment_id, join_code, created_by)
                       VALUES (%s,%s,%s,%s,%s,%s,%s)
                       ON CONFLICT (join_code) DO NOTHING RETURNING *""",
                       (f"{intake['company_name']} - {program_label(intake['form_type'])}",
                        intake['training_type'] or program_label(intake['form_type']),
                        program, intake_id, invoice['id'] if invoice else None,
                        _new_code(), created_by))
                cls = cur.fetchone()
                if cls:
                    break
            if not cls:
                raise RuntimeError('Could not allocate a unique class code. Try again.')
        cur.execute("""
            UPDATE corporate_intakes
               SET registration_token_hash=%s, registration_expires_at=NOW() + INTERVAL '30 days',
                   registration_revoked_at=NULL
             WHERE id=%s AND status IN ('open','ready')
        """, (_digest(token), intake_id))
        conn.commit()
        if with_class:
            return {'token': token, 'class_id': cls['id'], 'class_code': cls['join_code'],
                    'class_name': cls['name'], 'contact_email': intake['contact_email']}
        return token
    except Exception:
        conn.rollback()
        raise
    finally:
        cur.close(); conn.close()


