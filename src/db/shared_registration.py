def _registration_email_payload(cur, intake_id, url, class_id, origin, lock=False):
    """Validate scope and rebuild the URL; never trust a posted destination."""
    import re
    from urllib.parse import urlsplit
    from .lms import normalize_training_type
    from pricing import program_label
    try:
        expected, supplied = urlsplit(origin), urlsplit(url or '')
    except ValueError:
        return None, 'The registration URL is invalid.'
    match = re.fullmatch(r'/company/register/([A-Za-z0-9_-]+)', supplied.path)
    if ((expected.scheme, expected.netloc) != (supplied.scheme, supplied.netloc)
            or supplied.query or supplied.fragment or not match):
        return None, 'Use the registration link generated by this application.'
    cur.execute("""SELECT * FROM corporate_intakes
                     WHERE id=%s AND status IN ('open','ready')
                       AND registration_revoked_at IS NULL AND registration_expires_at > NOW()"""
                + (' FOR UPDATE' if lock else ''), (intake_id,))
    intake = cur.fetchone()
    if not intake or not intake['registration_token_hash'] or not secrets.compare_digest(
            _digest(match.group(1)), intake['registration_token_hash']):
        return None, 'The registration link is expired, revoked, replaced, or the intake is closed.'
    recipient = (intake['contact_email'] or '').strip()
    if not recipient or recipient.count('@') != 1 or any(c.isspace() for c in recipient):
        return None, 'The company contact needs a valid email address.'
    cur.execute("""SELECT id, join_code FROM training_classes
                     WHERE id=%s AND intake_id=%s AND join_open=TRUE AND program_code=%s"""
                + (' FOR SHARE' if lock else ''),
                (class_id, intake_id, normalize_training_type(intake['form_type'], intake['training_type'])))
    cls = cur.fetchone()
    if not cls:
        return None, 'This class is closed or does not belong to this intake and program.'
    canonical = f'{expected.scheme}://{expected.netloc}/company/register/{match.group(1)}'
    return {'registration_url': canonical, 'class_id': cls['id'], 'class_code': cls['join_code'],
            'to_email': recipient, 'company_name': intake['company_name'],
            'contact_person': intake['contact_person'], 'program_label': program_label(intake['form_type']),
            'expires_at': intake['registration_expires_at'].strftime('%d %b %Y')}, None


def registration_email_payload(intake_id, url, class_id, origin):
    """Current validated email content. Contains a secret URL; never log it."""
    conn = get_db(); cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
    try:
        return _registration_email_payload(cur, intake_id, url, class_id, origin)
    finally:
        cur.close(); conn.close()


def queue_registration_link_email(intake_id, url, class_id, origin, actor_id):
    """Commit encrypted content with its dedupe guard, before any transport call."""
    import json
    from secretbox import encrypt
    from .notifications import queue_notification
    conn = get_db(); cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
    try:
        payload, error = _registration_email_payload(cur, intake_id, url, class_id, origin, lock=True)
        if error:
            conn.rollback()
            return None, error
        # Encrypt before consuming the key: a missing encryption key must not
        # leave a notification whose link cannot ever be recovered for retry.
        stored = encrypt(json.dumps(payload))
        fingerprint = _digest(payload['registration_url'] + ':' + payload['class_code'] + ':' + payload['to_email'])
        nid = queue_notification(cur, intake_id, 'registration_link', payload['to_email'],
                                 'Company trainee registration - EnergyWize',
                                 f'registration:{intake_id}:{fingerprint}', created_by=actor_id)
        if nid is None:
            conn.rollback()
            return None, 'This link and class code already have a delivery record. Check Company notices and use Retry if needed.'
        cur.execute('UPDATE corporate_notifications SET payload=%s WHERE id=%s', (stored, nid))
        conn.commit()
        return nid, None
    except Exception:
        conn.rollback()
        raise
    finally:
        cur.close(); conn.close()


def registration_class_grant_valid(intake_id, class_id, code_hash):
    if not class_id or not code_hash:
        return False
    conn = get_db(); cur = conn.cursor()
    try:
        cur.execute("SELECT join_code FROM training_classes "
                    "WHERE id=%s AND intake_id=%s AND join_open=TRUE", (class_id, intake_id))
        row = cur.fetchone()
        return bool(row and secrets.compare_digest(_digest(row[0]), code_hash))
    finally:
        cur.close(); conn.close()


def enter_registration_with_class_code(link_token, email, code):
    """A class code selects the intake; a listed email selects one unused slot.

    This does not establish email ownership or identity, approve an applicant,
    create an account, mark payment, or enroll anybody in training.
    """
    from .classes import normalize_code
    from .lms import normalize_training_type
    code = normalize_code(code)
    if not email or not code or len(code) > 12:
        return None
    conn = get_db(); cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
    try:
        cur.execute("""SELECT id, form_type, training_type FROM corporate_intakes
                         WHERE registration_token_hash=%s AND registration_revoked_at IS NULL
                           AND registration_expires_at > NOW() AND status IN ('open','ready')
                         FOR UPDATE""", (_digest(link_token),))
        intake = cur.fetchone()
        if not intake:
            conn.rollback()
            return None
        cur.execute("""SELECT id, join_code FROM training_classes
                         WHERE intake_id=%s AND join_code=%s AND join_open=TRUE
                           AND program_code=%s FOR SHARE""",
                    (intake['id'], code, normalize_training_type(intake['form_type'], intake['training_type'])))
        cls = cur.fetchone()
        if not cls:
            conn.rollback()
            return None
        token = secrets.token_urlsafe(32)
        cur.execute("""UPDATE corporate_intake_slots
                          SET invite_token_hash=%s, invite_expires_at=NOW() + INTERVAL '30 minutes',
                              entry_class_id=%s, entry_link_hash=%s, entry_class_code_hash=%s,
                              entry_challenge_hash=NULL, entry_code_hash=NULL, entry_code_expires_at=NULL
                        WHERE intake_id=%s AND email_key=%s AND registration_id IS NULL
                          AND invite_used_at IS NULL AND invite_revoked_at IS NULL
                        RETURNING email_key""", (_digest(token), cls['id'], _digest(link_token), _digest(cls['join_code']),
                                                 intake['id'], email.strip().lower()))
        slot = cur.fetchone()
        if not slot:
            conn.rollback()
            return None
        conn.commit()
        return {'token': token, 'email_key': slot['email_key'], 'form_type': intake['form_type'],
                'class_id': cls['id'], 'class_code_hash': _digest(cls['join_code'])}
    except Exception:
        conn.rollback()
        raise
    finally:
        cur.close(); conn.close()


def request_registration_code(link_token, email, challenge, code):
    """10-minute email code, five guesses, at most one send per slot/minute.

    The raw random challenge stays in the applicant's signed session. Only
    hashes are stored, so the database alone cannot brute-force the short code.
    """
    conn = get_db(); cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
    try:
        cur.execute("""
            SELECT id FROM corporate_intakes
             WHERE registration_token_hash=%s AND registration_revoked_at IS NULL
               AND registration_expires_at > NOW() AND status IN ('open','ready')
             FOR UPDATE
        """, (_digest(link_token),))
        intake = cur.fetchone()
        if not intake:
            conn.rollback()
            return None
        cur.execute("""
            UPDATE corporate_intake_slots
               SET entry_challenge_hash=%s, entry_code_hash=%s,
                   entry_code_expires_at=NOW() + INTERVAL '10 minutes',
                   entry_code_sent_at=NOW(), entry_code_attempts=0
             WHERE intake_id=%s AND email_key=%s
               AND registration_id IS NULL AND invite_used_at IS NULL AND invite_revoked_at IS NULL
               AND (entry_code_sent_at IS NULL OR entry_code_sent_at < NOW() - INTERVAL '60 seconds')
            RETURNING email
        """, (_digest(challenge), _digest(challenge + ':' + code),
              intake['id'], email.strip().lower()))
        row = cur.fetchone()
        conn.commit()
        return dict(row) if row else None
    except Exception:
        conn.rollback()
        raise
    finally:
        cur.close(); conn.close()


def verify_registration_code(link_token, challenge, code):
    """Consume email proof once; issue a 30-minute submission grant."""
    conn = get_db(); cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
    try:
        cur.execute("""
            SELECT id, form_type FROM corporate_intakes
             WHERE registration_token_hash=%s AND registration_revoked_at IS NULL
               AND registration_expires_at > NOW() AND status IN ('open','ready')
             FOR UPDATE
        """, (_digest(link_token),))
        intake = cur.fetchone()
        if not intake:
            conn.rollback()
            return None
        cur.execute("""
            SELECT id, email_key, entry_code_hash FROM corporate_intake_slots
             WHERE intake_id=%s AND entry_challenge_hash=%s
               AND entry_code_expires_at > NOW() AND entry_code_attempts < 5
               AND registration_id IS NULL AND invite_used_at IS NULL AND invite_revoked_at IS NULL
             FOR UPDATE
        """, (intake['id'], _digest(challenge)))
        slot = cur.fetchone()
        if not slot:
            conn.rollback()
            return None
        cur.execute("UPDATE corporate_intake_slots SET entry_code_attempts=entry_code_attempts+1 WHERE id=%s", (slot['id'],))
        if not secrets.compare_digest(slot['entry_code_hash'], _digest(challenge + ':' + code)):
            conn.commit()
            return None
        token = secrets.token_urlsafe(32)
        cur.execute("""
            UPDATE corporate_intake_slots SET invite_token_hash=%s,
                   invite_expires_at=NOW() + INTERVAL '30 minutes',
                   entry_challenge_hash=NULL, entry_code_hash=NULL, entry_code_expires_at=NULL
             WHERE id=%s
        """, (_digest(token), slot['id']))
        conn.commit()
        return {'token': token, 'email_key': slot['email_key'], 'form_type': intake['form_type']}
    except Exception:
        conn.rollback()
        raise
    finally:
        cur.close(); conn.close()
